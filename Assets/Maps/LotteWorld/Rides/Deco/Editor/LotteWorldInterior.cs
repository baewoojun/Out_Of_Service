        void OnGUI()
        {
            if (on == null || on.Length != Rooms.Length) { on = new bool[Rooms.Length]; for (int i = 0; i < on.Length; i++) on[i] = true; }
            EditorGUILayout.LabelField("방 (끄면 안 놓음)", EditorStyles.boldLabel);
            EditorGUILayout.BeginHorizontal();
            if (GUILayout.Button("전부 켜기")) for (int i = 0; i < on.Length; i++) on[i] = true;
            if (GUILayout.Button("전부 끄기")) for (int i = 0; i < on.Length; i++) on[i] = false;
            EditorGUILayout.EndHorizontal();
            scroll = EditorGUILayout.BeginScrollView(scroll, GUILayout.Height(360));
            for (int i = 0; i < Rooms.Length; i++)
            {
                int n = Items.Count(it => it.room == i);
                on[i] = EditorGUILayout.ToggleLeft(Rooms[i].label + "  (" + n + "개)", on[i]);
            }
            EditorGUILayout.EndScrollView();
            if (GUILayout.Button("실내 꾸미기", GUILayout.Height(30))) Build(on);
            if (GUILayout.Button("꾸미기 지우기")) Clear();
            EditorGUILayout.HelpBox("LotteWorld_Interior 루트만 만들고 지웁니다. 저장은 직접 하세요(Ctrl+S).", MessageType.Info);
        }

        static GameObject FindRoot(string name)
        {
            foreach (GameObject g in SceneManager.GetActiveScene().GetRootGameObjects()) if (g.name == name) return g;
            return null;
        }
        static void Clear()
        {
            GameObject g = FindRoot(RootName);
            if (g != null) Undo.DestroyObjectImmediate(g);
            EditorSceneManager.MarkSceneDirty(SceneManager.GetActiveScene());
        }

        public static void Build(bool[] roomOn)
        {
            Clear();
            var root = new GameObject(RootName);
            Undo.RegisterCreatedObjectUndo(root, "Create " + RootName);
            var holders = new Transform[Rooms.Length];
            var cache = new Dictionary<string, GameObject>();
            var missing = new HashSet<string>();
            var counts = new int[Rooms.Length];
            int lights = 0;
            foreach (F it in Items)
            {
                if (roomOn != null && !roomOn[it.room]) continue;
                if (!cache.TryGetValue(it.n, out GameObject pf))
                {
                    string dir = it.n.StartsWith("Deco_") ? DecoDir : PropDir;
                    pf = AssetDatabase.LoadAssetAtPath<GameObject>(dir + "/" + it.n + ".prefab");
                    cache[it.n] = pf;
                }
                if (pf == null) { missing.Add(it.n); continue; }
                if (holders[it.room] == null)
                {
                    var h = new GameObject(Rooms[it.room].obj); h.transform.SetParent(root.transform, false); holders[it.room] = h.transform;
                }
                var g = (GameObject)PrefabUtility.InstantiatePrefab(pf, holders[it.room]);
                g.transform.position = new Vector3(it.x, it.y, it.z);
                g.transform.rotation = Quaternion.Euler(0f, it.yaw, 0f);
                lights += g.GetComponentsInChildren<Light>(true).Length;
                counts[it.room]++;
            }
            var lines = new List<string>();
            for (int i = 0; i < Rooms.Length; i++) if (counts[i] > 0) lines.Add("  " + Rooms[i].label + ": " + counts[i]);
            Debug.Log(string.Format("[Interior] 방 {0}곳, 소품 {1}개, 점광원 {2}개 -> {3}\n{4}", lines.Count, counts.Sum(), lights, RootName, string.Join("\n", lines)));
            if (missing.Count > 0)
                Debug.LogWarning("[Interior] 프리팹을 못 찾음: " + string.Join(", ", missing) + "\n  Props 창 [1. 프리팹 만들기]를 먼저 누르세요.");
            Selection.activeGameObject = root;
            EditorSceneManager.MarkSceneDirty(SceneManager.GetActiveScene());
        }
